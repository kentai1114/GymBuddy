export function getSwapOptions(exerciseId: string): Exercise[] {
  const current = getExercise(exerciseId)
  if (!current) return []
  const preferredIds = EASIER[exerciseId] ?? []
  const preferred = preferredIds
    .map((id) => getExercise(id))
    .filter((e): e is Exercise => Boolean(e))
  const seen = new Set<string>([exerciseId, ...preferred.map((e) => e.id)])
  const rest = EXERCISES.filter((e) => {
    if (seen.has(e.id)) return false
    return e.muscle === current.muscle && e.kind === current.kind
  }).sort((a, b) => {
    const rank = (x: Exercise) =>
      x.difficulty === 'beginner' ? 0 : x.difficulty === 'advanced' ? 2 : 1
    return rank(a) - rank(b)
  })
  return [...preferred, ...rest]
}

